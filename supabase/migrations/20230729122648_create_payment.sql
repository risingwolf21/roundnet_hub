create table public.payments_new (
    id bigint generated by default as identity,
    created_at timestamp with time zone null default now(),
    "userId" text null,
    state text not null default 'OPEN' :: text,
    "amountToPay" numeric not null default '0' :: numeric
) tablespace pg_default;

alter table
    public.payments_new
add
    constraint payments_new_pkey primary key (id);

alter table
    public.payments_new
add
    constraint payments_new_userid_fkey foreign key ("userId") references "user_new" ("userId");