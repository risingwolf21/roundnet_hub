create table public.user (
    created_at timestamp with time zone null default now(),
    "displayName" text not null default '' :: text,
    email text not null default '' :: text,
    "userId" text not null default '' :: text,
    verified boolean not null default false,
    role public.UserRole not null default 'user' :: UserRole,
    disabled boolean not null default false,
    permissions "Permissions" [] null,
    notifications "NotificationTags" [] null,
    constraint users_pkey primary key ("userId"),
    constraint users_userid_key unique ("userId")
) tablespace pg_default;

create table public.payments (
    id bigint generated by default as identity,
    created_at timestamp with time zone null default now(),
    "userId" text not null,
    "amountToPay" numeric not null default '0' :: numeric,
    "paymentState" public.PaymentState not null default 'Open' :: public.PaymentState,
    constraint payments_pkey primary key (id),
    constraint payments_userId_fkey foreign key ("userId") references "user" ("userId")
) tablespace pg_default;

create table public.keys (
    id bigint generated by default as identity,
    created_at timestamp with time zone not null default now(),
    name text null,
    constraint keys_pkey primary key (id)
) tablespace pg_default;

create table public.key_holders (
    "user" text not null,
    key bigint not null,
    "lastUpdate" timestamp with time zone null default now(),
    constraint key_holders_pkey primary key ("user", key),
    constraint key_holders_key_fkey foreign key (key) references keys (id) on update cascade on delete cascade,
    constraint key_holders_user_fkey foreign key ("user") references "user" ("userId") on update cascade on delete
    set
        null
) tablespace pg_default;

create table public.drink (
    id bigint generated by default as identity,
    name character varying null,
    price real null default '0' :: real,
    stock bigint null,
    "imageUrl" text null,
    active boolean not null default false,
    deleted boolean not null default false,
    "previousDrink" bigint null,
    type public.ProductType not null default 'None' :: public.ProductType,
    constraint drinks_pkey primary key (id)
) tablespace pg_default;

create table public.history (
    id bigint generated by default as identity,
    created_at timestamp with time zone null default now(),
    drink bigint not null,
    "user" text not null,
    count bigint not null,
    payment bigint not null,
    amount numeric not null default '0' :: numeric,
    constraint history_pkey primary key (id),
    constraint history_id_key unique (id),
    constraint history_drink_fkey foreign key (drink) references drink (id),
    constraint history_payment_fkey foreign key (payment) references payments (id),
    constraint history_user_fkey foreign key ("user") references "user" ("userId")
) tablespace pg_default;

create table public.event_group (
    id bigint generated by default as identity,
    created_at timestamp with time zone not null default now(),
    description text not null default '' :: text,
    name text not null default '' :: text,
    color text not null default '#000000' :: text,
    constraint event_group_pkey primary key (id)
) tablespace pg_default;

create table public.group_user_mapping (
    "group" bigint not null,
    "user" text not null,
    constraint group_user_mapping_pkey primary key ("group", "user"),
    constraint group_user_mapping_group_fkey foreign key ("group") references event_group (id),
    constraint group_user_mapping_user_fkey foreign key ("user") references "user" ("userId")
) tablespace pg_default;

create table public.events (
    id bigint generated by default as identity,
    created_at timestamp with time zone not null default now(),
    description text not null default '' :: text,
    "meetingDateTime" timestamp with time zone null,
    "startingDateTime" timestamp with time zone not null,
    title text not null default '' :: text,
    end_at timestamp with time zone null,
    key text not null default gen_random_uuid (),
    "isCancelled" boolean not null default false,
    place text null,
    recurrence public.EventRecurrence not null default 'None' :: public.EventRecurrence,
    "group" bigint null,
    "answerDeadline" timestamp with time zone null,
    "maxAttendees" numeric not null default '-1' :: numeric,
    constraint events_pkey primary key (id),
    constraint events_group_fkey foreign key ("group") references event_group (id) on delete
    set
        null
) tablespace pg_default;

create table public.event_comments (
    id bigint generated by default as identity,
    created_at timestamp with time zone not null default now(),
    "user" text not null,
    event bigint not null,
    comment text not null default '' :: text,
    "displayName" text not null default '' :: text,
    constraint event_comments_pkey primary key (id),
    constraint event_comments_event_fkey foreign key (event) references events (id) on delete cascade,
    constraint event_comments_user_fkey foreign key ("user") references "user" ("userId")
) tablespace pg_default;

create table public.event_attendance_user_mapping (
    "lastUpdate" timestamp with time zone not null default now(),
    "user" text not null,
    event bigint not null,
    state public."EventAttendance" not null default 'Unanswered' :: public."EventAttendance",
    constraint event_attendance_user_mapping_pkey primary key ("user", event),
    constraint event_attendance_user_mapping_event_fkey foreign key (event) references events (id) on delete cascade,
    constraint event_attendance_user_mapping_user_fkey foreign key ("user") references "user" ("userId") on delete
    set
        null
) tablespace pg_default;

create view public.distinct_event as
select
    distinct on (events.key) events.id,
    events.created_at,
    events.description,
    events."meetingDateTime",
    events."startingDateTime",
    events.title,
    events.end_at,
    events.key,
    events."isCancelled",
    events.place,
    events.recurrence,
    events."group",
    events."answerDeadline",
    events."maxAttendees"
from
    events
where
    (
        events.end_at > now()
        or events.end_at is null
    )
    and events.recurrence <> 'None' :: public.EventRecurrence
order by
    events.key,
    events.created_at desc;