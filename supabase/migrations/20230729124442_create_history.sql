create table public.history (
    id bigint generated by default as identity,
    created_at timestamp with time zone null default now(),
    drink bigint null,
    "user" text null,
    count bigint null,
    payment bigint null,
    amount numeric null default '0' :: numeric
) tablespace pg_default;

alter table
    public.history
add
    constraint history_pkey primary key (id);

alter table
    public.history
add
    constraint history_id_key unique (id);

alter table
    public.history
add
    constraint history_drink_fkey foreign key (drink) references drink (id);

alter table
    public.history
add
    constraint history_payment_fkey foreign key (payment) references payments (id);

alter table
    public.history
add
    constraint history_user_fkey foreign key ("user") references "user" ("userId");