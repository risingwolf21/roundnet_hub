create table
    public.key_history
(
    id            bigint generated by default as identity,
    created_at    timestamp with time zone not null default now(),
    "pastUser"    text null,
    "currentUser" text null,
    key           bigint null,
    constraint key_history_pkey primary key (id),
    constraint key_history_pastUser_fkey foreign key ("pastUser") references "user" ("userId"),
    constraint key_history_currentUser_fkey foreign key ("currentUser") references "user" ("userId"),
    constraint key_history_key_fkey foreign key (key) references keys (id)
) tablespace pg_default;

alter table "public"."key_history" enable row level security;

create
policy "Access to all users"
on "public"."key_history"
as permissive
for all
to authenticated
using (true)
with check (true);

create function add_key_history_entry()
    returns trigger
    language plpgsql
as $$
begin
insert into key_history("pastUser", "currentUser", key)
values (old.user, new.user, new.key);
return new;
end;
$$;

create trigger key_history_trigger
    after update
    on key_holders
    for each row
    execute function add_key_history_entry();