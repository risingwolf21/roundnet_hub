create table public.events (
    id bigint generated by default as identity,
    created_at timestamp with time zone null default now(),
    recurring text null,
    description text null,
    "meetingDateTime" timestamp with time zone null,
    "startingDateTime" timestamp with time zone null,
    location text null,
    title text null,
    end_at timestamp with time zone null
) tablespace pg_default;

alter table
    public.events
add
    constraint events_pkey primary key (id);

create table public.event_group (
    id bigint generated by default as identity,
    created_at timestamp with time zone null default now(),
    description text null,
    name text null
) tablespace pg_default;

alter table
    public.event_group
add
    constraint event_group_pkey primary key (id);

create table public.event_attendance_user_mapping (
    id bigint generated by default as identity,
    created_at timestamp with time zone null default now(),
    "user" text not null,
    event bigint not null,
    state text not null default 'DECLINED' :: text
) tablespace pg_default;

alter table
    public.event_attendance_user_mapping
add
    constraint event_attendance_user_mapping_pkey primary key (id);

alter table
    public.event_attendance_user_mapping
add
    constraint event_attendance_user_mapping_event_fkey foreign key (event) references events (id);

alter table
    public.event_attendance_user_mapping
add
    constraint event_attendance_user_mapping_user_fkey foreign key ("user") references "user" ("userId");

create table public.group_event_mapping (
    id bigint generated by default as identity,
    "group" bigint not null,
    "event" bigint not null
) tablespace pg_default;

alter table
    public.group_event_mapping
add
    constraint group_event_mapping_pkey primary key (id);

alter table
    public.group_event_mapping
add
    constraint group_event_mapping_event_fkey foreign key ("event") references events (id);

alter table
    public.group_event_mapping
add
    constraint group_event_mapping_group_fkey foreign key ("group") references event_group (id);

create table public.group_user_mapping (
    id bigint generated by default as identity,
    main_group bigint not null,
    "user" text not null
) tablespace pg_default;

alter table
    public.group_user_mapping
add
    constraint group_user_mapping_pkey primary key (id);

alter table
    public.group_user_mapping
add
    constraint group_user_mapping_main_group_fkey foreign key (main_group) references event_group (id);

alter table
    public.group_user_mapping
add
    constraint group_user_mapping_user_fkey foreign key ("user") references "user" ("userId");