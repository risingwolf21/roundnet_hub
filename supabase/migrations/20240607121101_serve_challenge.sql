create table public.challenge (
    id bigint generated by default as identity,
    created_at timestamp with time zone not null default now(),
    name text not null default '' :: text,
    description text not null default '' :: text,
    "group" bigint not null,
    constraint challenge_pkey primary key (id),
    constraint challenge_group_fkey foreign key ("group") references event_group (id)
) tablespace pg_default;

create table public.challenge_stats (
    id bigint generated by default as identity,
    last_update timestamp with time zone not null default now(),
    "user" text not null,
    count numeric not null default '0' :: numeric,
    challenge bigint not null,
    constraint challenge_stats_pkey primary key (id),
    constraint challenge_stats_challenge_fkey foreign key (challenge) references challenge (id),
    constraint challenge_stats_user_fkey foreign key ("user") references "user" ("userId")
) tablespace pg_default;

ALTER TYPE public."Permissions"
ADD
    VALUE 'use;challenges';

ALTER TYPE public."Permissions"
ADD
    VALUE 'view;challenges';

CREATE
OR REPLACE FUNCTION increase_challenge_stats_count (
    user_id TEXT,
    challenge_id numeric,
    amount NUMERIC
) RETURNS void AS $ $ declare stats_id numeric;

BEGIN
SELECT
    id INTO stats_id
FROM
    challenge_stats
WHERE
    "user" = user_id
    AND "challenge" = challenge_id;

if stats_id is null then
INSERT INTO
    challenge_stats ("user", "challenge", "count")
values
(user_id, challenge_id, amount) returning id into stats_id;

else
UPDATE
    challenge_stats
SET
    count = count + amount
WHERE
    "user" = user_id
    AND "challenge" = challenge_id;

end if;

END;

$ $ LANGUAGE plpgsql;